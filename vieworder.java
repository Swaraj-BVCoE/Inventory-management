    private void tcMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tcMouseClicked
        // TODO add your handling code here:
        int index = tc.getSelectedRow();
        TableModel model = tc.getModel();
        String id = model.getValueAt(index, 0).toString();
        DefaultTableModel omodel = (DefaultTableModel) to.getModel();
        omodel.setRowCount(0);

        try {
            Connection con = connectionprovider.getCon();
            Statement st = con.createStatement();
            java.sql.ResultSet re = st.executeQuery("select * from orderDetail where customer_fk=" + id + "");
            while (re.next()) {
                omodel.addRow(new Object[]{re.getString("orderId"), re.getString("orderDate"), re.getString("totalpaid")});
            }
        } catch (SQLException cp) {
            JOptionPane.showMessageDialog(null, cp);
        }
    }//GEN-LAST:event_tcMouseClicked

