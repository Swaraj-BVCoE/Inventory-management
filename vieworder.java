    private void formComponentShown(java.awt.event.ComponentEvent evt) {//GEN-FIRST:event_formComponentShown
        // TODO add your handling code here:
        DefaultTableModel model = (DefaultTableModel) tc.getModel();
        try {
            Connection con = connectionprovider.getCon();
            Statement st = con.createStatement();
            java.sql.ResultSet re = st.executeQuery("select * from customer");
            while (re.next()) {
                model.addRow(new Object[]{re.getString("customer_pk"), re.getString("name"), re.getString("mobilenumber"), re.getString("email")});
            }
        } catch (SQLException cp) {
            JOptionPane.showMessageDialog(null, cp);
        }

    }//GEN-LAST:event_formComponentShown

