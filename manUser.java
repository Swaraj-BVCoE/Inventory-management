    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        // TODO add your handling code here:
        String name = jTextField1.getText();
        String address = jTextField5.getText();
        String mobileno = jTextField2.getText();
        String password = jTextField4.getText();
        String email = jTextField3.getText();
        String status = (String) StatusB.getSelectedItem();
        if (validateFields("new")) {
            JOptionPane.showMessageDialog(null, "All field is required");
        } else {
            try {
                Connection con = connectionprovider.getCon();
                PreparedStatement pe = con.prepareStatement("insert into swaraj (userRole,name,mobileno,email,password,address,status) values ('Admin',?,?,?,?,?,?)");
                pe.setString(1, name);
                pe.setString(2, mobileno);
                pe.setString(3, email);
                pe.setString(4, password);
                pe.setString(5, address);
                pe.setString(6, status);
                pe.executeUpdate();
                JOptionPane.showMessageDialog(null, "user sucessfull");
                setVisible(false);
                new manUser().setVisible(true);
            } catch (SQLException e) {
                JOptionPane.showMessageDialog(null, e);
            }
        }
    }//GEN-LAST:event_jButton4ActionPerformed

