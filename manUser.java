    private void TabeluserMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TabeluserMouseClicked
        // TODO add your handling code here:
        int index = Tabeluser.getSelectedRow();
        TableModel model = Tabeluser.getModel();

        String id = model.getValueAt(index, 0).toString();
        appuserPk = Integer.parseInt(id);

        String name = model.getValueAt(index, 1).toString();
        jTextField1.setText(name);

        String mobileno = model.getValueAt(index, 2).toString();
        jTextField2.setText(mobileno);

        String email = model.getValueAt(index, 3).toString();
        jTextField3.setText(email);

        String address = model.getValueAt(index, 4).toString();
        jTextField5.setText(address);

        String status = model.getValueAt(index, 5).toString();
        StatusB.removeAllItems();
        if (status.equals("Active")) {
            StatusB.addItem("Active");
            StatusB.addItem("InActive");

        } else {
            StatusB.addItem("InActive");
            StatusB.addItem("Active");

        }

        jTextField4.setEditable(false);
        jTextField4.setBackground(Color.DARK_GRAY);

        jButton4.setEnabled(false);
        ud.setEnabled(true);


    }//GEN-LAST:event_TabeluserMouseClicked

    private void udActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_udActionPerformed
        // TODO add your handling code here:
        String name = jTextField1.getText();
        String address = jTextField5.getText();
        String mobileno = jTextField2.getText();
        String email = jTextField3.getText();
        String status = (String) StatusB.getSelectedItem();
        if (validateFields("edit")) {
            JOptionPane.showMessageDialog(null, "All field is required");
        } else {
            try {
                Connection con = connectionprovider.getCon();
                PreparedStatement pe = con.prepareStatement("update appuser set name=?,mobileno=?,email=?,address=?,status=? where appuser_pk=?");
                pe.setString(1, name);
                pe.setString(2, mobileno);
                pe.setString(3, email);
                pe.setString(4, address);
                pe.setString(5, status);
                pe.setInt(6, appuserPk);
                pe.executeUpdate();
                JOptionPane.showMessageDialog(null, "user updated  sucessfull");
                setVisible(false);
                new manUser().setVisible(true);
            } catch (SQLException e) {
                JOptionPane.showMessageDialog(null, e);
            }
        }
    }//GEN-LAST:event_udActionPerformed

