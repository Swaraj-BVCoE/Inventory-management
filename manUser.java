    private void formComponentShown(java.awt.event.ComponentEvent evt) {//GEN-FIRST:event_formComponentShown
        // TODO add your handling code here:
        DefaultTableModel model = (DefaultTableModel) Tabeluser.getModel();
        try {
            Connection con = connectionprovider.getCon();
            Statement st = con.createStatement();
            java.sql.ResultSet re = st.executeQuery("select * from  swaraj where userRole='Admin' ");
            while (re.next()) {
                model.addRow(new Object[]{re.getString("appuser_pk"), re.getString("name"), re.getString("mobileno"), re.getString("email"), re.getString("address"), re.getString("status")});
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, e);
        }
        ud.setEnabled(false);
    }//GEN-LAST:event_formComponentShown

