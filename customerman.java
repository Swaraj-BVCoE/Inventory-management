    private void cus_tableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_cus_tableMouseClicked
        // TODO add your handling code here:
        int index =cus_table.getSelectedRow();
        TableModel model =cus_table.getModel();
        String id=model.getValueAt(index,0).toString();
        customerPK = Integer.parseInt(id);
        
        String name1=model.getValueAt(index,1).toString();
        txtname.setText(name1);
        
        String mobilenumer=model.getValueAt(index,2).toString();
        txtnumber.setText(mobilenumer);
        
        String email=model.getValueAt(index,3).toString();
        txtmail.setText(email);
        Save.setEnabled(false);
        up.setEnabled(true);
         
    }//GEN-LAST:event_cus_tableMouseClicked

    private void formComponentShown(java.awt.event.ComponentEvent evt) {//GEN-FIRST:event_formComponentShown
        // TODO add your handling code here:
        DefaultTableModel model=(DefaultTableModel) cus_table.getModel();
        try {
          Connection con=connectionprovider.getCon();
            Statement st=con.createStatement();
            java.sql.ResultSet re =st.executeQuery("select * from customer ");
            while (re.next())
            {
             model.addRow(new Object[] {re.getString("name"),re.getString("mobilenumber"),re.getString("email")});
            }
        }
        catch(SQLException e)
        {
          JOptionPane.showMessageDialog(null, e);
        }
        up.setEnabled(false);
        
    }//GEN-LAST:event_formComponentShown

