    private void SaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SaveActionPerformed
        // TODO add your handling code here:
        String name=txtname.getText();
        String number=txtnumber.getText();
        String mail=txtmail.getText();
        if (validateFields())
        {
            JOptionPane.showMessageDialog(null,"All fields are required");
        }
        else
        {
            try
            {
            Connection con=connectionprovider.getCon();
            PreparedStatement pe=con.prepareStatement("insert into customer (name,mobilenumber,email) values(?,?,?)");
            pe.setString(1,name);
            pe.setString(2,number);
            pe.setString(3,mail);
            
            pe.executeUpdate();
             JOptionPane.showMessageDialog(null,"customer  Added sucessfully");
             setVisible(false);
            
             new customerman().setVisible(true);
            }
            catch(SQLException e)
            {
                JOptionPane.showMessageDialog(null,e);
            }
        }
    }//GEN-LAST:event_SaveActionPerformed

