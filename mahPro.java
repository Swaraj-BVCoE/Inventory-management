    private void saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveActionPerformed
        // TODO add your handling code here:
        String namee=name.getText();
        String quantitye=quantity.getText();
        String pricee=price.getText();
        String  desc=des.getText();
        String category =(String) CateCo.getSelectedItem();
        String categoryId[]=category.split("-",0);
        if (validateFields("new"))
        {
            JOptionPane.showMessageDialog(null,"All fields are required");
        }
        else
        {
            try
            {
               Connection con=connectionprovider.getCon();
            PreparedStatement pe=con.prepareStatement("insert into product (name,quantity,price,des,category_fk) values(?,?,?,?,?)");
            pe.setString(1,namee);
            pe.setString(2,quantitye);
            pe.setString(3,pricee);
            pe.setString(4,desc);
            pe.setString(5,categoryId[0]);
            pe.executeUpdate();
             JOptionPane.showMessageDialog(null,"Product Added sucessfully");
             setVisible(false);
            
             new mahPro().setVisible(true);
            }
            catch(SQLException e)
            {
                JOptionPane.showMessageDialog(null,e);
            }
        }
    }//GEN-LAST:event_saveActionPerformed

