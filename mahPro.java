    private boolean validateFields(String formType)
    {
        if(formType.equals("edit") && !name.getText().equals("") && !price.getText().equals("") && !des.getText().equals(""))
        {
            return false;
        }
        else if(formType.equals("new") && !name.getText().equals("") && !price.getText().equals("") && !des.getText().equals("") && !quantity.getText().equals(""))
        {
            return false;
        }
        else
        {
            return true;
        }
    }

