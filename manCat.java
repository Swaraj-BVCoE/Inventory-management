    private void JupdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_JupdateActionPerformed
        // TODO add your handling code here:
        String name = Jname.getText();
        if (validateFields()) {
            JOptionPane.showMessageDialog(null, "All filds aare required");
        } else {
            try {
                Connection con = connectionprovider.getCon();
                PreparedStatement pe = con.prepareStatement("update category_user set name=? where cateto_pk=?");
                pe.setString(1, name);
                pe.setInt(2, categorypk);
                pe.executeUpdate();
                JOptionPane.showMessageDialog(null, "category updated sucess");
                setVisible(false);
                new manCat().setVisible(true);
            } catch (SQLException e) {
                JOptionPane.showMessageDialog(null, "hello");
            }
        }

    }//GEN-LAST:event_JupdateActionPerformed

    private void tableCteMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tableCteMouseClicked
        // TODO add your handling code here:
        int index = tableCte.getSelectedRow();
        TableModel model = tableCte.getModel();
        String id = model.getValueAt(index, 0).toString();
        categorypk = Integer.parseInt(id);

        String name = model.getValueAt(index, 1).toString();
        Jname.setText(name);
        Jsave.setEnabled(false);
        Jupdate.setEnabled(true);
    }//GEN-LAST:event_tableCteMouseClicked

