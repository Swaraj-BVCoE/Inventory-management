    private void formComponentShown(java.awt.event.ComponentEvent evt) {//GEN-FIRST:event_formComponentShown
        // TODO add your handling code here:
        DefaultTableModel model = (DefaultTableModel) tableCte.getModel();
        try {
            Connection con = connectionprovider.getCon();
            Statement st = con.createStatement();
            java.sql.ResultSet re = st.executeQuery("select * from category_user");
            while (re.next()) {
                model.addRow(new Object[]{re.getString("cateto_pk"), re.getString("name")});
            }

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(null, "");
        }
        Jupdate.setEnabled(false);
    }//GEN-LAST:event_formComponentShown

    private void JsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_JsaveActionPerformed
        // TODO add your handling code here:
        String name = Jname.getText();
        if (validateFields()) {
            JOptionPane.showMessageDialog(null, "All filds aare required");
        } else {
            try {
                Connection con = connectionprovider.getCon();
                PreparedStatement pe = con.prepareStatement("insert into category_user (name) values (?)");
                pe.setString(1, name);
                pe.executeUpdate();
                JOptionPane.showMessageDialog(null, "category added sucess");
                setVisible(false);
                new manCat().setVisible(true);
            } catch (SQLException e) {
                JOptionPane.showMessageDialog(null, "hello");
            }
        }
    }//GEN-LAST:event_JsaveActionPerformed

